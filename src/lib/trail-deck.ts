/**
 * THE HODL TRAIL · event deck (content module).
 *
 * Pure data: the engine (lib/hodl-trail) picks one event per era per
 * UTC day. Content rules — enforced by scripts/test-hodl-trail.ts, so
 * a bad entry is a build failure, not a vibe:
 *
 * BALANCE BANDS (per choice):
 *   stake  0..1     fraction of the stack committed (0 on slider rows ·
 *                   the player's 0–100% dial replaces it)
 *   risk   0.05..0.8  chance-space the day's shared roll bites
 *   boomX  0.02..0.8  gain multiplier on the staked sats when it misses
 *   bustX  0.2..1     fraction of staked sats lost when it hits
 *   deathRisk only where risk ≥ 0.35 AND bustX ≥ 0.5 · max one per event
 *   ≤1 slider choice per event · ≥1 choice with risk ≤ 0.2 (a safe out)
 *   2–4 choices per event
 *
 * DESIGN SOUL: score is denominated in SATS, not dollars. "Sell and
 * buy back cheaper" is a sat-GAIN when history says the top was in ·
 * knowing WHICH scary choice history rewarded is the skill. Labels may
 * feel degen while numbers quietly reward the historically literate.
 *
 * PROSE RULES: wry second person, era-accurate, ≤320 chars, no em
 * dashes, ZERO borrowed franchise prose (never the word "dysentery",
 * never the string "Oregon Trail" · IP ship gate, tested).
 *
 * Deck edits reshuffle the CURRENT day's seeded picks · deploy content
 * batches right after UTC rollover (see lib/hodl-trail header).
 */

