// Generates src/lib/iso-countries.ts — the FULL ISO-3166-1 alpha-2 table.
//
// Why this exists (2026-08-20): the /submit country dropdown was built
// from COUNTRIES, which by design holds ONLY countries that already have
// a vendor. A merchant from country #21 therefore could not state their
// country at all, even though /api/submit-vendor has always accepted any
// /^[A-Z]{2}$/. The ceiling was the form, not the backend.
//
// COUNTRIES stays vendor-bearing-only. It drives the country filter
// pills, the vendor map dots, and — critically — generateStaticParams for
// the 20 /spend-bitcoin-in/[country] hub pages. Widening it to ~250 rows
// would stand up hundreds of empty hub pages: thin content, actively
// harmful. So the wide list lives here and is used ONLY where a wide list
// belongs (the submit form, the add-vendor CLI).
//
// Author-time, not runtime. A runtime Intl.DisplayNames call would risk a
// hydration mismatch — SubmitForm is "use client" but still SSR'd, and
// Node's ICU can disagree with the browser's on a region name.
//
// CLDR common names ("United States"), never ISO official names ("United
// States of America"): the official forms would produce hub slugs like
// united-states-of-america and break canonical URLs on promotion.
//
// Run: node scripts/build-iso-countries.mjs

import { readFileSync, writeFileSync } from "node:fs";

// ISO 3166-1 alpha-2, officially assigned.
const CODES = `AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP KE KG KH KI KM KN KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM PN PR PS PT PW PY QA RE RO RS RU RW SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ UA UG UM US UY UZ VA VC VE VG VI VN VU WF WS YE YT ZA ZM ZW`
  .trim()
  .split(/\s+/);

const dn = new Intl.DisplayNames(["en"], { type: "region" });
const flagFor = (cc) =>
  String.fromCodePoint(...[...cc].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));

const names = {};
for (const code of CODES) {
  const label = dn.of(code);
  if (!label || label === code) {
    throw new Error(`no CLDR name for ${code} — refusing to emit a code-as-label row`);
  }
  names[code] = label;
}

// ROUND-TRIP GATE. The 20 rows in COUNTRIES are load-bearing: their
// labels become hub slugs. If a future ICU bump renames one, this build
// must fail loudly rather than silently move a canonical URL.
const src = readFileSync("src/lib/vendors.ts", "utf8");
const block = src.match(
  /export const COUNTRIES: Record<string, \{ flag: string; label: string \}> = \{([\s\S]*?)\n\};/,
);
if (!block) throw new Error("could not locate COUNTRIES in src/lib/vendors.ts");

const rows = [...block[1].matchAll(/(\w{2}):\s*\{\s*flag:\s*"([^"]+)",\s*label:\s*"([^"]+)"\s*\}/g)];
if (rows.length === 0) throw new Error("COUNTRIES parsed to zero rows");

const drift = [];
for (const [, code, flag, label] of rows) {
  if (!names[code]) drift.push(`${code}: absent from the ISO table`);
  else if (names[code] !== label) drift.push(`${code}: COUNTRIES says "${label}", CLDR says "${names[code]}"`);
  if (flagFor(code) !== flag) drift.push(`${code}: derived flag ${flagFor(code)} != hand-typed ${flag}`);
}
if (drift.length) {
  throw new Error(
    `COUNTRIES/ISO drift — a hub slug or flag would move:\n  ${drift.join("\n  ")}\n` +
      `Fix the mismatch deliberately (see LABEL_OVERRIDES in src/lib/iso-countries.ts) before regenerating.`,
  );
}

const body = Object.entries(names)
  .map(([code, label]) => `  ${code}: ${JSON.stringify(label)},`)
  .join("\n");

writeFileSync(
  "src/lib/iso-countries.ts",
  `// GENERATED by scripts/build-iso-countries.mjs — do not edit by hand.
// Regenerate: node scripts/build-iso-countries.mjs
//
// The FULL ISO-3166-1 alpha-2 table (${CODES.length} rows), used ONLY where a
// wide list belongs: the /submit country dropdown and the add-vendor CLI.
//
// This is NOT the display registry. COUNTRIES in src/lib/vendors.ts stays
// vendor-bearing-only (currently ${rows.length} rows) because it drives the
// country filter pills, the map dots, and generateStaticParams for the
// /spend-bitcoin-in/[country] hub pages. A country becomes a hub only when
// a vendor actually lands there — see scripts/promote-country.ts.
//
// Names are CLDR common forms, asserted at build time to round-trip against
// every label in COUNTRIES, so a regeneration can never silently rename a
// country and move its canonical hub URL.

export const ISO_COUNTRY_NAMES: Record<string, string> = {
${body}
};

/**
 * Flag emoji from an alpha-2 code, by regional-indicator arithmetic.
 *
 * Verified against all ${rows.length} hand-typed flags in COUNTRIES: the derivation
 * reproduces every one byte-for-byte, which is why this table carries no
 * emoji column of its own.
 */
export function flagFor(code: string): string {
  const cc = code.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(cc)) return "";
  return String.fromCodePoint(
    ...[...cc].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  );
}

/** True when the code is an officially assigned ISO-3166-1 alpha-2 country. */
export function isIsoCountry(code: string): boolean {
  return Object.prototype.hasOwnProperty.call(
    ISO_COUNTRY_NAMES,
    code.trim().toUpperCase(),
  );
}
`,
);

console.log(`✓ src/lib/iso-countries.ts — ${CODES.length} codes, ${rows.length}/${rows.length} COUNTRIES rows round-tripped`);
